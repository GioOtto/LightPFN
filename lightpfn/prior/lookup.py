"""High-cardinality lookup columns: an opt-in post-processing of graph classification tasks (CPU only).

With probability `lookup_probability` a finished task gets one discrete column with K levels (log-uniform,
Zipf-like frequencies) whose effect on the target is a random table of per-level logits. The new target is
drawn from softmax(a * table[level] + b * centered one-hot(graph target)): the graph signal stays, attenuated.
The column is exposed either as a typed categorical (mask True) or as a plain numeric column whose code order is
arbitrary (mask False). Every draw comes from a separate seed namespace: the base task is exactly the task of the
same spec without the flag, and without the flag nothing here runs (pools stay byte-identical).

Version 2 (2026-11-04), after the 256-task pilot of version 1 (runs/analysis_lookup_20261102/prior_pilot):
- learnable levels that do not drown the graph: at least 8 rows per level on average (K <= n/8: 1000 levels need
  8000-row tables, i.e. the long-context stages), per-level effects a 1.0-2.5 and a stronger graph term b 2.5-5.
  Version 1 (2 rows per level, a 1-3, b 0-3) left CatBoost at AUC .569 without the column; pilots of 4 November
  (runs/analysis_lookup_20261102/prior_pilot/PILOT_V2.md): the column is worth +0.053 AUC to CatBoost (61% of
  tasks > .02), the table without it loses .149 against the base task;
- the class shares stay the base task's: per-class logit offsets are fitted so the expected shares equal the base
  counts (version 1 moved the binary minority median from .197 to .397), and a balanced v4 target keeps >= 10%;
- the lookup never turns a predictable table into an unpredictable one: when the base table passes the OOB/Brier
  unpredictability filter, the final table must pass it too (graph v3 filters its quantized source, so its final
  table may fail the filter; then the check is not applied, as for the base). A rejected draw is redrawn, and after
  max_target_draws the task keeps no lookup column (never force-accepted).
"""
import math

import numpy as np

# Persist the entire policy in meta.json; changing it requires a new version.
CONFIG = dict(
    version=2, levels=[32, 1000], min_rows_per_level=8, zipf_exponent=[0.0, 1.2],
    lookup_weight=[1.0, 2.5], graph_weight=[2.5, 5.0], typed_probability=0.5,
    max_target_draws=16, seed_namespace=0x4C4B5550,
    marginals="per-class logit offsets: expected class shares equal the base task's", offset_iterations=60,
    balanced_min_share=0.10,
    refilter="lightpfn.prior.generate._unpredictable (OOB/Brier, default PriorConfig) on the final table, "
             "applied when the base final table passes it",
    fallback="no lookup column after max_target_draws rejected draws",
)


def matched_offsets(logits, share, iterations):
    """Fit mean softmax shares with a fixed iteration budget (all shares > 0)."""
    share = np.asarray(share, dtype=float)
    if (share.shape != (logits.shape[1],) or not np.isfinite(share).all()
            or np.any(share <= 0) or not np.isclose(share.sum(), 1)):
        raise ValueError("class shares must be positive, finite and sum to one")
    beta = np.zeros(logits.shape[1])
    for _ in range(iterations):
        z = logits + beta
        prob = np.exp(z - z.max(1, keepdims=True))
        prob /= prob.sum(1, keepdims=True)
        mean = prob.mean(0)
        if np.any(mean < np.finfo(float).tiny):
            # A whole class can underflow even with a stable row-wise softmax.
            # Keep the ordinary path unchanged, including its generated bytes.
            log_prob = z - z.max(1, keepdims=True)
            log_prob -= np.log(np.exp(log_prob).sum(1, keepdims=True))
            log_mean = np.logaddexp.reduce(log_prob, axis=0) - math.log(len(logits))
            beta += np.log(share) - log_mean
        else:
            beta += np.log(share / mean)
        beta -= beta.mean()
    return beta


def add_lookup_column(task, spec, probability):
    seed = spec["seed"]
    if isinstance(seed, (int, np.integer)):
        seed = [int(seed)]
    rng = np.random.default_rng(np.random.SeedSequence([*seed, CONFIG["seed_namespace"]]))
    task = dict(task, lookup_column=-1, lookup_levels=0, lookup_typed=False)
    if rng.random() >= probability:
        return task
    X, y, cat = task["X"], task["y"].astype(np.int64), task["cat_mask"]
    n, C = len(y), spec["n_classes"]
    # At least min_rows_per_level rows per nominal level on average, not a per-level minimum.
    high = min(CONFIG["levels"][1], n // CONFIG["min_rows_per_level"])
    if high < CONFIG["levels"][0]:
        return task
    K = int(round(math.exp(rng.uniform(math.log(CONFIG["levels"][0]), math.log(high)))))
    p = np.arange(1, K + 1, dtype=float) ** -rng.uniform(*CONFIG["zipf_exponent"])
    p = rng.permutation(p / p.sum())
    a, b = rng.uniform(*CONFIG["lookup_weight"]), rng.uniform(*CONFIG["graph_weight"])
    table = rng.normal(size=(K, C))
    graph = np.eye(C)[y] - 1 / C
    share = np.bincount(y, minlength=C) / n
    typed = bool(rng.random() < CONFIG["typed_probability"])
    position = rng.random()  # keep the location fixed while redrawing levels, targets and code permutations
    balanced = bool(task.get("balanced_target", False))
    from lightpfn.prior.generate import _unpredictable
    refilter = not _unpredictable(X, y, None, return_metrics=True)["reject"]
    for _ in range(CONFIG["max_target_draws"]):
        level = rng.choice(K, size=n, p=p)
        logits = a * table[level] + b * graph
        logits = logits + matched_offsets(logits, share, CONFIG["offset_iterations"])
        prob = np.exp(logits - logits.max(1, keepdims=True))
        prob /= prob.sum(1, keepdims=True)
        new_y = np.minimum((rng.random(n)[:, None] > np.cumsum(prob, axis=1)).sum(1), C - 1)
        counts = np.bincount(new_y, minlength=C)
        if counts.min() < 2 or len(np.unique(level)) < 2:
            continue
        if balanced and counts.min() / n < CONFIG["balanced_min_share"]:
            continue
        built = _place(task, spec, level, K, typed, position, rng)
        if refilter and _unpredictable(built[0], new_y, None, return_metrics=True)["reject"]:
            continue
        break
    else:
        return task
    X, cat, j, codes = built
    task.update(X=X, y=new_y.astype(np.uint8), cat_mask=cat, lookup_column=j, lookup_levels=K,
                lookup_typed=typed)
    if codes is not None:
        task["cat_codes"] = codes
    return task


def _place(task, spec, level, K, typed, position, rng):
    """The table with the lookup column inserted (or replacing a column at full width): X, mask, index, codes."""
    X, cat = task["X"], task["cat_mask"]
    # Arbitrary code order: the stored value carries no ordinal information about the effect.
    code = rng.permutation(K)[level]
    legacy_typed = "cat_codes" in task  # graph v3 typed: X holds scaled values, level IDs stored apart
    if typed and not legacy_typed:
        value = code.astype(np.float64)  # graph v4 convention: categorical values are exact level IDs
    else:
        value = (code - code.mean()) / max(code.std(ddof=1), 1e-6)
    column = value.astype(np.float16)
    # Count distinct values in float32: numpy 2.5.2 np.sort/np.unique on float16 can return unsorted output on
    # AVX-512 CPUs (AMD EPYC 9655 on the 2026-11-04 box: 45 "distinct" values for 37 levels). Exact widening.
    if len(np.unique(column.astype(np.float32))) != len(np.unique(code)):
        raise RuntimeError("lookup levels collide after the float16 cast")
    d, codes = X.shape[1], None
    if d < spec["n_features"]:
        j = min(int(position * (d + 1)), d)
        X = np.insert(X, j, column, axis=1)
        cat = np.insert(cat, j, typed)
        if legacy_typed:
            codes = np.insert(task["cat_codes"], j, code if typed else -1, axis=1)
    else:
        j = min(int(position * d), d - 1)
        X, cat = X.copy(), cat.copy()
        X[:, j], cat[j] = column, typed
        if legacy_typed:
            codes = task["cat_codes"].copy()
            codes[:, j] = code if typed else -1
    return X, cat, j, codes
