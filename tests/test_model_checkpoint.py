@pytest.mark.parametrize("mode", ["eval", "train"])
@pytest.mark.parametrize("padded", [False, True])
@torch.no_grad()
def test_r2_default_exact(mode, padded):
    path = Path(__file__).resolve().parents[1] / "runs/train/r2/ema_step015000.pt"
    if not path.is_file():
        pytest.skip("optional historical checkpoint is not distributed")
    ck = torch.load(path, map_location="cpu", weights_only=False)
    model = LightPFN(Config())
    assert model.state_dict().keys() == ck["ema"].keys()
    model.load_state_dict(ck["ema"], strict=True)
    assert sum(p.numel() for p in model.parameters()) == 4_777_072
    getattr(model, mode)()
    g = torch.Generator().manual_seed(817)
    x = torch.randn(2, 13, 5, generator=g)
    x[0, 2, 1] = float("nan")
    x[1, :, 2] = 1.
    x[1, 10, 4] = float("nan")
    y = torch.randint(0, 3, (2, 9), generator=g)
    y[:, :3] = torch.arange(3)
    d = torch.tensor([3, 5]) if padded else None
    out = model(x, y, d=d, n_classes=3)
    expected = torch.tensor(EXPECTED[mode, padded])
    assert torch.equal(out, expected), (out - expected).abs().max().item()
